let registered = false

export function registerModelsRegistryI18n() {
  if (registered) {
    return
  }
  i18n.addResourceBundle('en', 'translation', { settings: { modelsRegistry: en } }, true, true)
  i18n.addResourceBundle('zh', 'translation', { settings: { modelsRegistry: zh } }, true, true)
  registered = true
}

export const modelsRegistryKey = (suffix: string) => `settings.modelsRegistry.${suffix}`
